"""Render Claude's analysis as Markdown the editor reads next to the clip."""

from __future__ import annotations

from typing import Any

_FLAG = {"ja": "🇯🇵", "en": "🇬🇧", "id": "🇮🇩", "ko": "🇰🇷", "zh": "🇨🇳", "es": "🇪🇸"}


def ts(seconds: float | None) -> str:
    if seconds is None:
        return "–"
    s = max(0.0, float(seconds))
    return f"{int(s // 60):02d}:{int(s % 60):02d}"


def _cell(text: Any) -> str:
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip() or " "


def render_moment(a: dict[str, Any], meta: dict[str, Any]) -> str:
    titles = a.get("titles") or []
    head = titles[0]["text"] if titles else meta.get("title", "")
    cut = a.get("cut") or {}
    thumb = a.get("thumbnail") or {}
    song = a.get("song") or None
    music = a.get("music_copyright") or {}
    out = [
        f"# #{meta['rank']} · {head}",
        "",
        f"**Stream:** {meta.get('title')}  ",
        f"**Stream time:** {meta['stream_range'][0]}–{meta['stream_range'][1]} · "
        f"[watch on YouTube]({meta.get('youtube_url')})  ",
        f"**Category:** {a.get('category')} · **Clip-worthiness:** {a.get('clip_worthiness')}/10 · "
        f"**Format:** {a.get('format')}",
    ]
    if song:
        out.append(f"**Song:** {song.get('title')} — {song.get('artist')}")
    out += ["", "## What happens", a.get("summary", ""), "",
            f"**Context:** {a.get('context', '')}", "",
            f"**Why it works:** {a.get('why_it_works', '')}", ""]

    out += ["## Cut"]
    if cut.get("long_in") is not None and cut.get("long_out") is not None:
        out.append(f"- **Long-form (16:9):** {ts(cut['long_in'])} → {ts(cut['long_out'])} "
                   f"({int(cut['long_out'] - cut['long_in'])}s)")
    if cut.get("short_in") is not None and cut.get("short_out") is not None:
        out.append(f"- **Short (9:16):** {ts(cut['short_in'])} → {ts(cut['short_out'])} "
                   f"({int(cut['short_out'] - cut['short_in'])}s) · crop: {a.get('vertical_crop', '')}")
    else:
        out.append("- **Short:** not recommended")
    if cut.get("notes"):
        out.append(f"- **Trim notes:** {cut['notes']}")
    out += [f"- **Hook (first 3s):** {a.get('hook', '')}", ""]

    out += ["## Titles"]
    out += [f"- {_FLAG.get(t.get('lang', ''), t.get('lang', ''))} {t.get('text', '')}" for t in titles]
    out += ["", "## Thumbnail",
            f"- **Frame:** `{thumb.get('frame_file', '')}`",
            f"- **Text:** {thumb.get('text', '')}",
            f"- **Notes:** {thumb.get('notes', '')}", ""]

    out += ["## Storyboard", "", "| Time | Beat | On screen | Line | Text overlay | Edit |",
            "|---|---|---|---|---|---|"]
    for b in a.get("storyboard") or []:
        out.append(f"| {ts(b.get('start'))}–{ts(b.get('end'))} | {_cell(b.get('beat'))} | "
                   f"{_cell(b.get('on_screen'))} | {_cell(b.get('line'))} | "
                   f"{_cell(b.get('text_overlay'))} | {_cell(b.get('edit'))} |")
    caps = a.get("captions") or []
    if caps:
        out += ["", "## Captions", "", "| Time | Original | Translation |", "|---|---|---|"]
        out += [f"| {ts(c.get('at'))} | {_cell(c.get('original'))} | {_cell(c.get('translation'))} |"
                for c in caps]
    out += ["", "## Notes",
            f"- **Music copyright:** {music.get('risk', 'none')}"
            + (f" — {music['note']}" if music.get("note") else ""),
            f"- **Tags:** {', '.join(a.get('tags') or [])}",
            "",
            f"_Times are from the start of `{meta['clip']['file']}`. Generated by chat-watcher with "
            f"Claude ({meta.get('model', '?')}); check it before publishing._", ""]
    return "\n".join(out)


def render_digest(d: dict[str, Any], stream: dict[str, Any], moments: dict[int, dict[str, Any]]) -> str:
    def label(rank: int) -> str:
        m = moments.get(rank)
        if not m:
            return f"#{rank}"
        title = next((t["text"] for t in m["analysis"].get("titles", [])), "")
        return f"#{rank} [{m['stream_range']}] {title} → `{m['folder']}`"

    out = [f"# {stream.get('title')}", "",
           f"**Channel:** {stream.get('channel')} · **Type:** {stream.get('stream_type')} · "
           f"[YouTube](https://youtu.be/{stream.get('video_id')})", "",
           "## The stream", d.get("stream_summary", ""), "",
           "## Highlights video order"]
    out += [f"{i}. {label(r)}" for i, r in enumerate(d.get("highlights_order") or [], 1)]
    out += ["", "## Compilation titles"]
    out += [f"- {_FLAG.get(t.get('lang', ''), t.get('lang', ''))} {t.get('text', '')}"
            for t in d.get("compilation_titles") or []]
    out += ["", "## Best Shorts"]
    out += [f"- {label(r)}" for r in d.get("best_shorts") or []] or ["- none"]
    if d.get("skip"):
        out += ["", "## Not worth editing"] + [f"- {label(r)}" for r in d["skip"]]
    out += ["", "## Notes", d.get("notes", ""), ""]
    return "\n".join(out)
